const RESERVOIRS = [KYIV_RESERVOIR, KREMENCHUK_RESERVOIR, DNIPRODZERZHYNSK_RESERVOIR, KAKHOVKA_RESERVOIR];

function addRiversLayer(map) {
    const isDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    const color = isDark ? '#6ea8fe' : '#3f8fc0';
    const layer = L.layerGroup();

    L.polyline(DNIPRO_COURSE, {
        className: 'river-line',
        color,
        weight: 3,
        opacity: 0.85,
        lineJoin: 'round',
        smoothFactor: 1.5,
    }).addTo(layer);

    RESERVOIRS.forEach((ring) => {
        L.polygon(ring, {
            className: 'river-area',
            color,
            weight: 1,
            opacity: 0.85,
            fillColor: color,
            fillOpacity: 0.55,
            smoothFactor: 1.5,
        }).addTo(layer);
    });

    layer.addTo(map);
    return layer;
}

