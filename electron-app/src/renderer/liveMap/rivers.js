function addRiversLayer(map) {
    const isDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    const layer = L.layerGroup();
    L.polyline(DNIPRO_COURSE, {
        className: 'river-line',
        color: isDark ? '#6ea8fe' : '#3f8fc0',
        weight: 3,
        opacity: 0.85,
        lineJoin: 'round',
        smoothFactor: 1.5,
    }).addTo(layer);
    layer.addTo(map);
    return layer;
}

