function buildRaionGroup(language) {
    const layer = L.layerGroup();
    const isEnglish = language === 'English';

    RAIONS.forEach((raion) => {
        L.marker([raion.lat, raion.lng], {
            icon: L.divIcon({
                className: 'raion-label',
                html: isEnglish ? raion.en : raion.uk,
                iconSize: null,
            }),
            interactive: false,
        }).addTo(layer);
    });

    return layer;
}

